"""Generate Flatcap exports from src/theme.json. Python 3 standard library only."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/theme.json"


def load():
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def prop(key):
    return "--fc-" + key.replace(".", "-")


def declarations(values, indent="  "):
    return [f"{indent}{prop(key)}: {value};" for key, value in values.items()]


def css(data):
    lines = [f"/* Flatcap {data['version']} · GENERATED by scripts/build.py; edit src/theme.json. */",
             "/* Tokens only: no reset, font downloads, components, or legacy numbered aliases. */", ":root {"]
    for values in [data["themes"]["slate"], data["typography"], data["metrics"],
                   data["density"]["comfortable"], data["elevation"]["slate"]]:
        lines.extend(declarations(values))
    lines += ["  --fc-color-scheme: dark;", "}", "", ':root[data-fc-theme="daylight"] {']
    lines += declarations(data["themes"]["daylight"]) + declarations(data["elevation"]["daylight"])
    lines += ["  --fc-color-scheme: light;", "}", "", "@media (prefers-color-scheme: light) {",
              '  :root[data-fc-theme="system"] {']
    lines += declarations(data["themes"]["daylight"], "    ") + declarations(data["elevation"]["daylight"], "    ")
    lines += ["    --fc-color-scheme: light;", "  }", "}", "", ':root[data-fc-contrast="more"] {']
    overrides = {key.removeprefix("contrast."): f"var({prop(key)})"
                 for key in data["themes"]["slate"] if key.startswith("contrast.")}
    lines += declarations(overrides)
    lines += ["}", "", "@media (prefers-contrast: more) {", '  :root[data-fc-contrast="system"] {']
    lines += declarations(overrides, "    ")
    lines += ["  }", "}", "", ':root[data-fc-density="compact"] {']
    lines += declarations(data["density"]["compact"])
    lines += ["}", "", "@media (prefers-reduced-motion: reduce) {", "  :root { --fc-motion-fast: 0ms; }", "}", ""]
    return "\n".join(lines)


def sass_map(values, indent="  ", colors=False):
    return "\n".join(f'{indent}{json.dumps(key)}: {value if colors else json.dumps(value)},'
                     for key, value in values.items())


def scss(data):
    parts = [f"// Flatcap {data['version']} · GENERATED by scripts/build.py; edit src/theme.json.",
             '// Import with @use: no CSS is emitted until a mixin is included.',
             '@use "sass:map";', '@use "sass:string";', '', '$themes: (']
    for mode, values in data["themes"].items():
        parts += [f'  "{mode}": (', sass_map(values, "    ", colors=True), '  ),']
    parts += [');', '', '$foundation: (', sass_map({**data['typography'], **data['metrics']}), ');', '', '$densities: (']
    for density, values in data['density'].items():
        parts += [f'  "{density}": (', sass_map(values, "    "), '  ),']
    parts += [');', '', '$elevation: (']
    for mode, values in data['elevation'].items():
        parts += [f'  "{mode}": (', sass_map(values, "    "), '  ),']
    parts += [');', '', '''@function color($role, $theme: "slate", $contrast: "standard") {
  @if not map.has-key($themes, $theme) { @error "Unknown Flatcap theme: #{$theme}"; }
  @if $contrast != "standard" and $contrast != "more" { @error "Unknown Flatcap contrast: #{$contrast}"; }
  $palette: map.get($themes, $theme);
  @if $contrast == "more" and map.has-key($palette, "contrast.#{$role}") {
    @return map.get($palette, "contrast.#{$role}");
  }
  @if not map.has-key($palette, $role) { @error "Unknown Flatcap color role: #{$role}"; }
  @return map.get($palette, $role);
}

@function value($name) {
  @if not map.has-key($foundation, $name) { @error "Unknown Flatcap foundation token: #{$name}"; }
  @return string.unquote(map.get($foundation, $name));
}

// Emit resolved tokens into the caller's selector; no system media-query behavior.
@mixin tokens($theme: "slate", $contrast: "standard", $density: "comfortable") {
  @if not map.has-key($themes, $theme) { @error "Unknown Flatcap theme: #{$theme}"; }
  @if not map.has-key($densities, $density) { @error "Unknown Flatcap density: #{$density}"; }
  @each $key, $raw in $foundation { --fc-#{string-replace($key, ".", "-")}: #{string.unquote($raw)}; }
  @each $key, $raw in map.get($themes, $theme) {
    --fc-#{string-replace($key, ".", "-")}: #{color($key, $theme, $contrast)};
  }
  @each $key, $raw in map.get($densities, $density) { --fc-#{string-replace($key, ".", "-")}: #{string.unquote($raw)}; }
  @each $key, $raw in map.get($elevation, $theme) { --fc-#{string-replace($key, ".", "-")}: #{string.unquote($raw)}; }
  @if $theme == "slate" { --fc-color-scheme: dark; } @else { --fc-color-scheme: light; }
}

@function string-replace($text, $search, $replacement) {
  $index: string.index($text, $search);
  @if $index {
    @return string.slice($text, 1, $index - 1) + $replacement + string-replace(string.slice($text, $index + string.length($search)), $search, $replacement);
  }
  @return $text;
}
''']
    return "\n".join(parts)


def svg_colors(text, data):
    """Only color explicitly annotated geometry. Geometry and provenance are preserved."""
    roles = data["branding"]["roles"]
    palette = {**data["themes"][data["branding"]["theme"]], **data["branding"]["colors"]}

    def update(match):
        tag = match.group(0)
        role = re.search(r'data-fc-role="([^"]+)"', tag)
        if not role:
            return tag
        color = palette[roles[role.group(1)]]
        if not re.search(r'\sfill="#[0-9A-Fa-f]{6}"', tag):
            raise ValueError(f"Missing explicit fill for branding role {role.group(1)}")
        return re.sub(r'(\sfill=")#[0-9A-Fa-f]{6}', lambda m: m.group(1) + color, tag)

    # Keep the quote and all other attributes untouched.
    return re.sub(r'<(?:path|circle|rect)\b[^>]*>', update, text)


def palette_doc(data):
    lines = ["# Flatcap palette and tokens", "", f"Version {data['version']}. Generated from `src/theme.json` with `python3 scripts/build.py`; do not edit this table by hand.", "",
             "Opaque sRGB values. Roles describe purpose, even when their hex values match. Use each role on the appropriate surface; see the [accessibility guidelines](accessibility.md).", "",
             "| Role | CSS variable | Slate | Daylight |", "| --- | --- | --- | --- |"]
    for key, color in data["themes"]["slate"].items():
        lines.append(f"| `{key}` | `{prop(key)}` | `{color}` | `{data['themes']['daylight'][key]}` |")
    for title, values in [("Typography", data["typography"]), ("Metrics", data["metrics"])]:
        lines += ["", f"## {title}", "", "| Token | CSS variable | Value |", "| --- | --- | --- |"]
        lines += [f"| `{k}` | `{prop(k)}` | `{v}` |" for k, v in values.items()]
    lines += ["", "## Density", "", "| Token | Comfortable | Compact |", "| --- | --- | --- |"]
    lines += [f"| `{k}` | `{v}` | `{data['density']['compact'][k]}` |" for k, v in data['density']['comfortable'].items()]
    lines += ["", "The Condensed family is independent of spacing density. `motion.fast` resolves to `0ms` in the generated CSS when the system requests reduced motion. Shadows live in `elevation`; they do not identify controls on their own.", ""]
    return "\n".join(lines)


def outputs(data):
    from validate import integrity
    integrity(data)
    files = {ROOT / "src/theme.css": css(data), ROOT / "src/theme.scss": scss(data),
             ROOT / "docs/palette.md": palette_doc(data)}
    for filename in ["logo.svg", "readme_logo.svg"]:
        path = ROOT / "src" / filename
        files[path] = svg_colors(path.read_text(encoding="utf-8"), data)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale generated files; do not write")
    args = parser.parse_args()
    stale = []
    for path, content in outputs(load()).items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if args.check and stale:
        parser.exit(1, "Stale generated files: " + ", ".join(stale) + "\nRun python3 scripts/build.py\n")
    print("Generated files are current" if args.check else f"Updated {len(stale)} generated files")


if __name__ == "__main__":
    main()
